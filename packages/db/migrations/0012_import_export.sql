-- CSV / XLSX import and export (MVP_SPEC §M8, ADR-0029).
--
-- Four tables:
--   import_jobs    one row per uploaded file, carrying the whole state machine
--   import_rows    the parsed rows, staged so the chunked import can restart
--   import_errors  one row per row that failed, which becomes the error file
--   export_jobs    one row per requested export
--
-- Nothing here stores a file. Files live in object storage under a random key
-- and move browser <-> store on presigned URLs (CLAUDE.md §5.12); these rows
-- only say that a file exists and what has happened to it.
--
-- Every table is created empty, so no index build takes a long lock.

-- ---------------------------------------------------------------------------
-- 1. import_jobs
-- ---------------------------------------------------------------------------
CREATE TABLE import_jobs (
  id               uuid PRIMARY KEY,
  tenant_id        uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  object_type      text NOT NULL,
  status           text NOT NULL DEFAULT 'awaiting_upload',

  file_name        text NOT NULL,
  -- What the uploader said (from the filename) and what the bytes say. The two
  -- must agree, or the job is rejected (CLAUDE.md §5.12).
  claimed_format   text NOT NULL,
  detected_format  text,
  -- Random, generated by the server. Never derived from the filename.
  storage_key      text NOT NULL,
  size_bytes       bigint,
  -- A retried POST returns the job it already made rather than a second one.
  idempotency_key  text,

  -- Header cells and the first few rows, for the mapping screen.
  columns          jsonb,
  preview          jsonb,
  -- [{ "column": 0, "field": "email" }, ...], validated against
  -- field_definitions and the actor's field permissions before it is stored.
  mapping          jsonb,
  duplicate_mode   text,
  match_field      text,

  total_rows       integer,
  -- The checkpoint. Advanced in the same transaction as the chunk it covers,
  -- which is the entire idempotency story (ADR-0029).
  processed_rows   integer NOT NULL DEFAULT 0,
  created_count    integer NOT NULL DEFAULT 0,
  updated_count    integer NOT NULL DEFAULT 0,
  skipped_count    integer NOT NULL DEFAULT 0,
  failed_count     integer NOT NULL DEFAULT 0,

  error_file_key   text,
  -- A sentence safe to show the user. Never a stack trace or a driver message.
  failure_reason   text,
  started_at       timestamptz,
  finished_at      timestamptz,

  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  created_by       uuid,
  updated_by       uuid,

  CONSTRAINT import_jobs_object_type_chk
    CHECK (object_type IN ('account', 'contact', 'lead')),
  CONSTRAINT import_jobs_status_chk CHECK (status IN (
    'awaiting_upload', 'analyzing', 'awaiting_mapping', 'staging',
    'processing', 'completed', 'failed', 'rejected'
  )),
  CONSTRAINT import_jobs_claimed_format_chk CHECK (claimed_format IN ('csv', 'xlsx')),
  CONSTRAINT import_jobs_detected_format_chk
    CHECK (detected_format IS NULL OR detected_format IN ('csv', 'xlsx')),
  CONSTRAINT import_jobs_duplicate_mode_chk
    CHECK (duplicate_mode IS NULL OR duplicate_mode IN ('skip', 'update', 'create')),
  CONSTRAINT import_jobs_file_name_chk CHECK (length(file_name) BETWEEN 1 AND 255),
  CONSTRAINT import_jobs_counts_chk CHECK (
    processed_rows >= 0 AND created_count >= 0 AND updated_count >= 0
    AND skipped_count >= 0 AND failed_count >= 0
  ),
  -- Every processed row is exactly one of created, updated, skipped or failed.
  -- If this ever stops holding, a retry double-counted a chunk.
  CONSTRAINT import_jobs_counts_add_up_chk CHECK (
    created_count + updated_count + skipped_count + failed_count = processed_rows
  ),
  CONSTRAINT import_jobs_progress_chk CHECK (
    total_rows IS NULL OR processed_rows <= total_rows
  ),
  -- A mapped, running job has said what to do about duplicates.
  CONSTRAINT import_jobs_started_chk CHECK (
    status NOT IN ('staging', 'processing', 'completed')
    OR (mapping IS NOT NULL AND duplicate_mode IS NOT NULL)
  ),
  CONSTRAINT import_jobs_tenant_id_key UNIQUE (tenant_id, id),
  CONSTRAINT import_jobs_storage_key_key UNIQUE (storage_key)
);

CREATE INDEX import_jobs_tenant_created_idx
  ON import_jobs (tenant_id, created_at DESC, id);
CREATE INDEX import_jobs_tenant_creator_idx
  ON import_jobs (tenant_id, created_by, created_at DESC);
CREATE UNIQUE INDEX import_jobs_idempotency_key
  ON import_jobs (tenant_id, created_by, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

-- The state machine, in the database (the pattern 0008 uses for deal stages).
-- A job can only move forward, only along these edges, and its checkpoint and
-- counters can never go backwards. The worker and the API both write this row,
-- so the rule cannot live in either of them alone.
CREATE FUNCTION import_jobs_assert_transition() RETURNS trigger
  LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.status IN ('completed', 'failed', 'rejected') THEN
    RAISE EXCEPTION 'import job % is % and cannot change', OLD.id, OLD.status
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.status <> OLD.status AND NOT (
       (OLD.status = 'awaiting_upload' AND NEW.status IN ('analyzing', 'rejected'))
    OR (OLD.status = 'analyzing'       AND NEW.status IN ('awaiting_mapping', 'rejected', 'failed'))
    OR (OLD.status = 'awaiting_mapping' AND NEW.status IN ('staging', 'rejected'))
    OR (OLD.status = 'staging'         AND NEW.status IN ('processing', 'rejected', 'failed'))
    OR (OLD.status = 'processing'      AND NEW.status IN ('completed', 'failed'))
  ) THEN
    RAISE EXCEPTION 'import job % cannot go from % to %', OLD.id, OLD.status, NEW.status
      USING ERRCODE = 'check_violation';
  END IF;

  IF NEW.processed_rows < OLD.processed_rows
     OR NEW.created_count < OLD.created_count
     OR NEW.updated_count < OLD.updated_count
     OR NEW.skipped_count < OLD.skipped_count
     OR NEW.failed_count < OLD.failed_count THEN
    RAISE EXCEPTION 'import job % progress cannot go backwards', OLD.id
      USING ERRCODE = 'check_violation';
  END IF;

  -- The identity of the job and the file never change after creation.
  IF NEW.tenant_id <> OLD.tenant_id
     OR NEW.object_type <> OLD.object_type
     OR NEW.storage_key <> OLD.storage_key
     OR NEW.created_by IS DISTINCT FROM OLD.created_by THEN
    RAISE EXCEPTION 'import job % identity is immutable', OLD.id
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END
$$;

CREATE TRIGGER import_jobs_transition
  BEFORE UPDATE ON import_jobs
  FOR EACH ROW EXECUTE FUNCTION import_jobs_assert_transition();

GRANT EXECUTE ON FUNCTION import_jobs_assert_transition() TO crm_app, crm_worker;

-- ---------------------------------------------------------------------------
-- 2. import_rows: the parsed file, staged
-- ---------------------------------------------------------------------------
-- A chunk event reads `row_number > checkpoint ORDER BY row_number LIMIT n`.
-- Re-parsing the file for every chunk would be quadratic, and XLSX has no
-- random access, so the rows are parsed once and kept here until the job ends.
-- Deleted in the transaction that completes or fails the job.
CREATE TABLE import_rows (
  id          uuid PRIMARY KEY,
  tenant_id   uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  job_id      uuid NOT NULL,
  -- The data row's ordinal, 1..n with no gaps. This is what the checkpoint counts,
  -- so a blank line in the file cannot desynchronise it from `processed_rows`.
  row_number  integer NOT NULL,
  -- The row number the user sees in their spreadsheet (the header is row 1).
  -- What an error message names, so "row 4,207" means row 4,207 in *their* file.
  source_row  integer NOT NULL,
  -- The cells, as strings, in column order.
  cells       jsonb NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid,
  updated_by  uuid,

  CONSTRAINT import_rows_job_fkey FOREIGN KEY (tenant_id, job_id)
    REFERENCES import_jobs (tenant_id, id) ON DELETE CASCADE,
  CONSTRAINT import_rows_row_number_chk CHECK (row_number >= 1 AND source_row >= 2),
  CONSTRAINT import_rows_job_row_key UNIQUE (job_id, row_number)
);

CREATE INDEX import_rows_tenant_job_idx ON import_rows (tenant_id, job_id, row_number);

-- ---------------------------------------------------------------------------
-- 3. import_errors
-- ---------------------------------------------------------------------------
CREATE TABLE import_errors (
  id          uuid PRIMARY KEY,
  tenant_id   uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  job_id      uuid NOT NULL,
  row_number  integer NOT NULL,
  -- The target field the problem is about, when there is one.
  field       text,
  message     text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  created_by  uuid,
  updated_by  uuid,

  CONSTRAINT import_errors_job_fkey FOREIGN KEY (tenant_id, job_id)
    REFERENCES import_jobs (tenant_id, id) ON DELETE CASCADE,
  CONSTRAINT import_errors_message_chk CHECK (length(message) BETWEEN 1 AND 500)
);

CREATE INDEX import_errors_tenant_job_idx ON import_errors (tenant_id, job_id, row_number);

-- ---------------------------------------------------------------------------
-- 4. export_jobs
-- ---------------------------------------------------------------------------
CREATE TABLE export_jobs (
  id              uuid PRIMARY KEY,
  tenant_id       uuid NOT NULL REFERENCES tenants (id) ON DELETE CASCADE,
  object_type     text NOT NULL,
  status          text NOT NULL DEFAULT 'queued',
  format          text NOT NULL,
  -- The list query the export was asked for: { filter, sort, q }. Stored so the
  -- worker runs exactly what the API validated, and so an audit reader can see
  -- what was exported.
  query           jsonb NOT NULL DEFAULT '{}'::jsonb,
  storage_key     text NOT NULL,
  row_count       integer,
  size_bytes      bigint,
  failure_reason  text,
  -- After this the download link is refused and the file is swept.
  expires_at      timestamptz NOT NULL,
  started_at      timestamptz,
  finished_at     timestamptz,
  idempotency_key text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  created_by      uuid,
  updated_by      uuid,

  CONSTRAINT export_jobs_object_type_chk
    CHECK (object_type IN ('account', 'contact', 'lead', 'deal')),
  CONSTRAINT export_jobs_status_chk
    CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  CONSTRAINT export_jobs_format_chk CHECK (format IN ('csv', 'xlsx')),
  CONSTRAINT export_jobs_storage_key_key UNIQUE (storage_key),
  CONSTRAINT export_jobs_tenant_id_key UNIQUE (tenant_id, id)
);

CREATE INDEX export_jobs_tenant_creator_idx
  ON export_jobs (tenant_id, created_by, created_at DESC);
CREATE UNIQUE INDEX export_jobs_idempotency_key
  ON export_jobs (tenant_id, created_by, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Row-Level Security and grants (0004)
--
-- Asymmetric on purpose. The API creates a job, reads it back, and moves it
-- along the first steps of its life; it never sees a staged row or an error
-- row, because those carry the contents of somebody's file and the only route
-- to them is the downloadable error file. The worker does the work.
-- ---------------------------------------------------------------------------
CALL apply_tenant_rls('import_jobs');
CALL apply_tenant_rls('import_rows');
CALL apply_tenant_rls('import_errors');
CALL apply_tenant_rls('export_jobs');

GRANT SELECT, INSERT, UPDATE ON import_jobs TO crm_app;
GRANT SELECT, INSERT, UPDATE ON import_jobs TO crm_worker;

GRANT SELECT, INSERT, UPDATE, DELETE ON import_rows TO crm_worker;
GRANT SELECT, INSERT, DELETE ON import_errors TO crm_worker;

GRANT SELECT, INSERT ON export_jobs TO crm_app;
GRANT SELECT, INSERT, UPDATE ON export_jobs TO crm_worker;
