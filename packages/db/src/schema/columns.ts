import { sql } from 'drizzle-orm';
import { customType, integer, jsonb, timestamp, uuid } from 'drizzle-orm/pg-core';

/**
 * Column building blocks shared by every table (CLAUDE.md §7).
 *
 * Defined once so a new table cannot accidentally omit `tenant_id`, get the
 * timestamp type wrong, or forget optimistic locking. A table that does not use
 * these is a table to look at twice in review.
 */

/**
 * Case-insensitive text. Emails are compared and deduplicated constantly, and
 * doing that with `lower()` everywhere eventually misses a call site; `citext`
 * makes it a property of the column instead.
 */
export const citext = customType<{ data: string; driverData: string }>({
  dataType: () => 'citext',
});

/** UTC instants. Postgres stores `timestamptz` as an absolute point in time. */
export function timestamptz(name: string) {
  return timestamp(name, { withTimezone: true, mode: 'date' });
}

/** Present on every table. */
export const baseColumns = {
  /** UUIDv7, generated by the application (ADR-0003). */
  id: uuid('id').primaryKey(),
  tenantId: uuid('tenant_id').notNull(),
  createdAt: timestamptz('created_at')
    .notNull()
    .default(sql`now()`),
  updatedAt: timestamptz('updated_at')
    .notNull()
    .default(sql`now()`),
  /** Null when written by the system rather than by a user (seeds, migrations). */
  createdBy: uuid('created_by'),
  updatedBy: uuid('updated_by'),
};

/**
 * Additional columns on mutable business records.
 *
 * `version` drives optimistic locking: an UPDATE carries the version the client
 * read, and a mismatch means someone else saved first. Without it, two reps
 * editing the same contact silently overwrite each other (MVP_SPEC M4).
 *
 * `deletedAt` is a soft delete feeding the 30-day Recycle Bin.
 */
export const recordColumns = {
  ownerId: uuid('owner_id'),
  deletedAt: timestamptz('deleted_at'),
  version: integer('version').notNull().default(1),
  /** Values for this tenant's custom fields (ADR-0004). GIN indexed. */
  customFields: jsonb('custom_fields')
    .$type<Record<string, unknown>>()
    .notNull()
    .default(sql`'{}'::jsonb`),
};
